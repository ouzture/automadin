"""Generate the public command catalogue from Automadin command metadata."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "automadin" / "resources" / "command_types.json"
OUTPUT = ROOT / "docs" / "user-guide" / "reference" / "commands.md"

CATEGORY_ORDER = (
    "ORGANIZATION",
    "ACTIONS",
    "DETECTION",
    "CONTROL_FLOW",
    "TIMING",
    "BROWSER",
    "ANDROID",
    "WINDOWS",
)


def _text(value: object) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ").strip()


def _default(value: object) -> str:
    if value is None:
        return "—"
    if isinstance(value, str):
        return f"`{_text(value)}`" if value else "empty text"
    return f"`{_text(json.dumps(value, ensure_ascii=False))}`"


def _choices(parameter: dict[str, Any]) -> str:
    options = parameter.get("options")
    if not isinstance(options, list) or not options:
        return "—"
    labels = parameter.get("option_labels", {})
    if not isinstance(labels, dict):
        labels = {}
    rendered = [str(labels.get(option, option)) for option in options]
    return ", ".join(f"`{_text(item)}`" for item in rendered)


def render(commands: list[dict[str, Any]]) -> str:
    by_category: dict[str, list[dict[str, Any]]] = {}
    for command in commands:
        by_category.setdefault(str(command["category"]), []).append(command)

    unknown = sorted(set(by_category) - set(CATEGORY_ORDER))
    categories = [*CATEGORY_ORDER, *unknown]
    lines = [
        "<!-- Generated by tools/generate_command_reference.py. Do not edit directly. -->",
        "",
        "# Command reference",
        "",
        f"Automadin currently provides **{len(commands)} commands**. This page is generated",
        "from the same metadata used by the flow editor, so labels, descriptions, options,",
        "and defaults remain aligned with the application.",
        "",
        "Some commands expose additional shared step controls such as comments, breakpoints,",
        "error policy, retries, minimum wait, and hook bindings. Those controls are described",
        "in [Build flows](../building-flows.md).",
        "",
    ]

    for category in categories:
        items = by_category.get(category, [])
        if not items:
            continue
        title = category.replace("_", " ").title()
        lines.extend([f"## {title}", ""])
        for command in items:
            lines.extend(
                [
                    f"### {command['label']}",
                    "",
                    _text(command.get("description", "")) or "No description provided.",
                    "",
                ]
            )
            traits: list[str] = []
            if command.get("canHaveChildren"):
                traits.append("accepts child commands")
            if command.get("canHaveElse"):
                traits.append("supports an Else branch")
            if command.get("collapseChildren"):
                traits.append("children are collapsed by default")
            if traits:
                lines.extend([f"**Structure:** {', '.join(traits)}.", ""])

            params = command.get("params", [])
            if not isinstance(params, list) or not params:
                lines.extend(["No command-specific parameters.", ""])
                continue
            lines.extend(
                [
                    "| Parameter | Type | Required | Default | Choices / notes |",
                    "| --- | --- | --- | --- | --- |",
                ]
            )
            for parameter in params:
                required = "No" if parameter.get("optional") else "Yes"
                notes: list[str] = []
                choices = _choices(parameter)
                if choices != "—":
                    notes.append(choices)
                if parameter.get("supportsValueReference"):
                    notes.append("supports a value reference")
                allowed = parameter.get("allowed_value_types")
                if isinstance(allowed, list) and allowed:
                    notes.append("value types: " + ", ".join(map(str, allowed)))
                if "min" in parameter or "max" in parameter:
                    notes.append(
                        f"range: {parameter.get('min', '—')} to {parameter.get('max', '—')}"
                    )
                lines.append(
                    "| "
                    + " | ".join(
                        (
                            _text(parameter.get("label", parameter.get("name", ""))),
                            f"`{_text(parameter.get('type', ''))}`",
                            required,
                            _default(parameter.get("default")) if "default" in parameter else "—",
                            "; ".join(notes) or "—",
                        )
                    )
                    + " |"
                )
            lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if output is stale")
    args = parser.parse_args()
    commands = json.loads(SOURCE.read_text(encoding="utf-8"))
    if not isinstance(commands, list):
        raise SystemExit("Command metadata root must be a list")
    content = render(commands)
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != content:
            raise SystemExit(
                "Generated command reference is stale; run "
                "python tools/generate_command_reference.py"
            )
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(content, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
